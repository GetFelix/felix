//! A peer that did not offer `ELECTION` is sent exactly what it was before
//! the capability existed.
//!
//! The vectors were produced by the build that predates `ELECTION`, so a
//! change to any existing layout, or an election field leaking onto a message
//! that does not carry one, fails here.

use super::*;

fn hex(frame: &[u8]) -> String {
    frame.iter().map(|byte| format!("{byte:02x}")).collect()
}

fn records(first_offset: u64, payloads: &[&'static [u8]]) -> ReplicateRecords {
    ReplicateRecords {
        correlation_id: 42,
        shard: shard(),
        first_offset,
        checksum: 0x0102_0304,
        payloads: payloads.iter().map(|p| Bytes::from_static(p)).collect(),
        marks: Vec::new(),
        publishers: Vec::new(),
        commit_offset: None,
        generations: None,
        times: None,
        set_generation: None,
    }
}

fn incarnated(mut shard: ShardRef) -> ShardRef {
    shard.incarnation = Some(5);
    shard
}

/// The messages beyond `every_message` that exercise the other kinds and the
/// incarnation envelope.
fn more() -> Vec<InternalMessage> {
    let generations = Some(vec![
        GenerationStart {
            generation: 6,
            start_offset: 100,
        },
        GenerationStart {
            generation: 7,
            start_offset: 101,
        },
    ]);
    let fence = |log, shard| {
        InternalMessage::Fence(Fence {
            correlation_id: 42,
            shard,
            log,
            election: None,
        })
    };
    let fetch = |labelled, timed, shard| {
        InternalMessage::ReplicateFetch(ReplicateFetch {
            correlation_id: 42,
            shard,
            log: ReplicaLog::Stream,
            from_offset: 100,
            max_bytes: 1 << 20,
            labelled,
            timed,
        })
    };
    let all_capabilities = PeerCapabilities::FENCE
        .union(PeerCapabilities::TAIL_FETCH)
        .union(PeerCapabilities::GENERATION_LABELS)
        .union(PeerCapabilities::FORWARD_OFFSETS)
        .union(PeerCapabilities::CACHE_FENCE)
        .union(PeerCapabilities::RECORD_TIMES)
        .union(PeerCapabilities::BALLOTS)
        .union(PeerCapabilities::PING)
        .union(PeerCapabilities::GROUP_FENCE)
        .union(PeerCapabilities::STORAGE_IDENTITY)
        .union(PeerCapabilities::NODE_INCARNATION)
        .union(PeerCapabilities::LANE_RENEWAL)
        .union(PeerCapabilities::FORWARD_INCARNATION)
        .union(PeerCapabilities::HEAD_TRIM);
    vec![
        fence(ReplicaLog::Cache, shard()),
        fence(ReplicaLog::Counters, shard()),
        fence(ReplicaLog::GroupCursors, incarnated(shard())),
        fence(ReplicaLog::Stream, incarnated(shard())),
        fetch(false, false, incarnated(shard())),
        fetch(true, false, shard()),
        fetch(true, true, shard()),
        InternalMessage::ReplicateRecords(ReplicateRecords {
            generations: generations.clone(),
            commit_offset: Some(90),
            ..records(100, &[b"a", b"bb"])
        }),
        InternalMessage::ReplicateRecords(ReplicateRecords {
            generations: generations.clone(),
            times: Some(vec![1_000, 2_000]),
            ..records(100, &[b"a", b"bb"])
        }),
        InternalMessage::ReplicateCacheRecords(ReplicateRecords {
            generations,
            commit_offset: Some(0),
            shard: incarnated(shard()),
            ..records(100, &[b"put"])
        }),
        InternalMessage::ReplicateRecords(ReplicateRecords {
            shard: incarnated(shard()),
            ..records(100, &[b"a"])
        }),
        InternalMessage::ReplicateRecords(ReplicateRecords {
            publishers: vec![Some(Bytes::from_static(b"alice"))],
            ..records(100, &[b"a"])
        }),
        InternalMessage::ForwardPublish(ForwardPublish {
            correlation_id: 42,
            shard: incarnated(shard()),
            ack: AckMode::OnCommit,
            payloads: vec![Bytes::from_static(b"a")],
            credential: String::new(),
        }),
        InternalMessage::ReplicateRebuild(ReplicateRebuild {
            correlation_id: 42,
            shard: shard(),
            log: ReplicaLog::GroupDeadLetters,
            base_offset: 5_000,
        }),
        InternalMessage::Hello(Hello {
            correlation_id: 42,
            node_id: "broker-a".to_string(),
            capabilities: Some(all_capabilities),
        }),
        InternalMessage::HelloOk(HelloOk {
            correlation_id: 42,
            node_id: "broker-b".to_string(),
            capabilities: Some(all_capabilities),
            identity: Some([7; 16]),
            incarnation: Some(9),
        }),
    ]
}

fn existing() -> Vec<InternalMessage> {
    let mut all = every_message();
    all.extend(more());
    all
}

/// Prints the vectors below. Run on the build that predates `ELECTION`:
/// `cargo test -p felix-wire print_byte_identity_vectors -- --ignored --nocapture`.
#[test]
#[ignore = "generates the vectors"]
fn print_byte_identity_vectors() {
    for message in existing() {
        println!("VECTOR {}", hex(&message.encode().expect("encode")));
    }
}

#[test]
fn every_message_that_predates_election_encodes_as_it_did() {
    let existing = existing();
    assert_eq!(existing.len(), VECTORS.len(), "a message was added or lost");
    for (index, (message, expected)) in existing.iter().zip(VECTORS).enumerate() {
        let frame = message.encode().expect("encode");
        assert_eq!(hex(&frame), *expected, "message {index}: {message:?}");
        assert_eq!(
            message.required_capability(),
            None,
            "message {index} would be withheld from a peer without ELECTION",
        );
        assert_eq!(&InternalMessage::decode(frame).expect("decode"), message);
    }
}

