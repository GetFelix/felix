// Prints one packet per line as `version name hex`, encoded by rumqttc.
use bytes::{Bytes, BytesMut};
use rumqttc::mqttbytes::{v4, QoS};
use rumqttc::v5::mqttbytes::v5 as m5;
use rumqttc::v5::mqttbytes::QoS as Q5;

fn hex(b: &BytesMut) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}
fn out(v: &str, name: &str, b: BytesMut) {
    println!("{v} {name} {}", hex(&b));
}
fn s(x: &str) -> String { x.to_string() }
fn up(k: &str, v: &str) -> (String, String) { (s(k), s(v)) }

fn main() {
    println!("# Encodings written by rumqttc 0.25.1, one per line: version, name, hex.");
    println!("# Generated by tests/vectors/rumqttc-gen; do not edit.");
    // ---- 3.1.1
    let mut b = BytesMut::new();
    v4::Connect::new("c1").write(&mut b).unwrap();
    out("v4", "connect_minimal", b);

    let mut c = v4::Connect::new("device-7");
    c.keep_alive = 60;
    c.clean_session = false;
    c.set_login("user", "pass");
    c.last_will = Some(v4::LastWill::new("will/topic", "bye", QoS::AtLeastOnce, true));
    let mut b = BytesMut::new();
    c.write(&mut b).unwrap();
    out("v4", "connect_will_login", b);

    for (n, rc, sp) in [
        ("connack_accepted", v4::ConnectReturnCode::Success, false),
        ("connack_session_present", v4::ConnectReturnCode::Success, true),
        ("connack_bad_version", v4::ConnectReturnCode::RefusedProtocolVersion, false),
        ("connack_bad_client_id", v4::ConnectReturnCode::BadClientId, false),
        ("connack_unavailable", v4::ConnectReturnCode::ServiceUnavailable, false),
        ("connack_bad_login", v4::ConnectReturnCode::BadUserNamePassword, false),
        ("connack_not_authorized", v4::ConnectReturnCode::NotAuthorized, false),
    ] {
        let mut b = BytesMut::new();
        v4::ConnAck::new(rc, sp).write(&mut b).unwrap();
        out("v4", n, b);
    }

    let mut p = v4::Publish::new("a/b", QoS::AtMostOnce, "hello");
    let mut b = BytesMut::new();
    p.write(&mut b).unwrap();
    out("v4", "publish_qos0", b);
    p.retain = true;
    let mut b = BytesMut::new();
    p.write(&mut b).unwrap();
    out("v4", "publish_qos0_retain", b);
    let mut p = v4::Publish::new("sensors/temp", QoS::AtLeastOnce, vec![1u8, 2, 3, 0, 255]);
    p.pkid = 10;
    let mut b = BytesMut::new();
    p.write(&mut b).unwrap();
    out("v4", "publish_qos1", b);
    p.dup = true;
    let mut b = BytesMut::new();
    p.write(&mut b).unwrap();
    out("v4", "publish_qos1_dup", b);
    let mut p = v4::Publish::new("x", QoS::ExactlyOnce, Vec::<u8>::new());
    p.pkid = 65535;
    let mut b = BytesMut::new();
    p.write(&mut b).unwrap();
    out("v4", "publish_qos2_empty", b);
    let big = vec![0xabu8; 200];
    let mut p = v4::Publish::new("big", QoS::AtMostOnce, big);
    p.retain = false;
    let mut b = BytesMut::new();
    p.write(&mut b).unwrap();
    out("v4", "publish_two_byte_length", b);

    let mut b = BytesMut::new();
    v4::PubAck::new(7).write(&mut b).unwrap();
    out("v4", "puback", b);
    let mut b = BytesMut::new();
    v4::PubRec::new(8).write(&mut b).unwrap();
    out("v4", "pubrec", b);
    let mut b = BytesMut::new();
    v4::PubRel::new(9).write(&mut b).unwrap();
    out("v4", "pubrel", b);
    let mut b = BytesMut::new();
    v4::PubComp::new(10).write(&mut b).unwrap();
    out("v4", "pubcomp", b);

    let mut sub = v4::Subscribe::new("a/+", QoS::AtLeastOnce);
    sub.pkid = 3;
    let mut b = BytesMut::new();
    sub.write(&mut b).unwrap();
    out("v4", "subscribe_one", b);
    let mut sub = v4::Subscribe::new_many(vec![
        v4::SubscribeFilter::new(s("a/#"), QoS::AtMostOnce),
        v4::SubscribeFilter::new(s("b/c"), QoS::ExactlyOnce),
        v4::SubscribeFilter::new(s("+/+/d"), QoS::AtLeastOnce),
    ]);
    sub.pkid = 4;
    let mut b = BytesMut::new();
    sub.write(&mut b).unwrap();
    out("v4", "subscribe_many", b);

    let mut b = BytesMut::new();
    v4::SubAck::new(
        4,
        vec![
            v4::SubscribeReasonCode::Success(QoS::AtMostOnce),
            v4::SubscribeReasonCode::Success(QoS::AtLeastOnce),
            v4::SubscribeReasonCode::Success(QoS::ExactlyOnce),
            v4::SubscribeReasonCode::Failure,
        ],
    )
    .write(&mut b)
    .unwrap();
    out("v4", "suback", b);

    let mut u = v4::Unsubscribe::new("a/b");
    u.pkid = 5;
    u.topics.push(s("c/d"));
    let mut b = BytesMut::new();
    u.write(&mut b).unwrap();
    out("v4", "unsubscribe", b);
    let mut b = BytesMut::new();
    v4::UnsubAck::new(5).write(&mut b).unwrap();
    out("v4", "unsuback", b);
    let mut b = BytesMut::new();
    v4::PingReq.write(&mut b).unwrap();
    out("v4", "pingreq", b);
    let mut b = BytesMut::new();
    v4::PingResp.write(&mut b).unwrap();
    out("v4", "pingresp", b);
    let mut b = BytesMut::new();
    v4::Disconnect.write(&mut b).unwrap();
    out("v4", "disconnect", b);

    // ---- 5.0
    let mut b = BytesMut::new();
    let c = m5::Connect {
        keep_alive: 30,
        client_id: s("c5"),
        clean_start: true,
        properties: None,
    };
    c.write(&None, &None, &mut b).unwrap();
    out("v5", "connect_minimal", b);

    let mut c = m5::Connect {
        keep_alive: 120,
        client_id: s("device-5"),
        clean_start: false,
        properties: Some(m5::ConnectProperties {
            session_expiry_interval: Some(3600),
            receive_maximum: Some(20),
            max_packet_size: Some(65536),
            topic_alias_max: Some(10),
            request_response_info: Some(1),
            request_problem_info: Some(0),
            user_properties: vec![up("k", "v"), up("k", "w")],
            authentication_method: Some(s("PLAIN")),
            authentication_data: Some(Bytes::from_static(b"\x00u\x00p")),
        }),
    };
    let will = m5::LastWill::new(
        "will/t",
        "gone",
        Q5::ExactlyOnce,
        false,
        Some(m5::LastWillProperties {
            delay_interval: Some(5),
            payload_format_indicator: Some(1),
            message_expiry_interval: Some(60),
            content_type: Some(s("text/plain")),
            response_topic: Some(s("resp/t")),
            correlation_data: Some(Bytes::from_static(b"corr")),
            user_properties: vec![up("a", "b")],
        }),
    );
    let login = m5::Login::new("user", "pass");
    let mut b = BytesMut::new();
    c.write(&Some(will), &Some(login), &mut b).unwrap();
    out("v5", "connect_full", b);
    c.properties = None;

    let mut b = BytesMut::new();
    m5::ConnAck {
        session_present: false,
        code: m5::ConnectReturnCode::Success,
        properties: None,
    }
    .write(&mut b)
    .unwrap();
    out("v5", "connack_minimal", b);
    let mut b = BytesMut::new();
    m5::ConnAck {
        session_present: true,
        code: m5::ConnectReturnCode::Success,
        properties: Some(m5::ConnAckProperties {
            session_expiry_interval: Some(100),
            receive_max: Some(32),
            max_qos: Some(1),
            retain_available: Some(1),
            max_packet_size: Some(1048576),
            assigned_client_identifier: Some(s("auto-1")),
            topic_alias_max: Some(16),
            reason_string: Some(s("ok")),
            user_properties: vec![up("x", "y")],
            wildcard_subscription_available: Some(1),
            subscription_identifiers_available: Some(1),
            shared_subscription_available: Some(0),
            server_keep_alive: Some(60),
            response_information: Some(s("resp")),
            server_reference: None,
            authentication_method: None,
            authentication_data: None,
        }),
    }
    .write(&mut b)
    .unwrap();
    out("v5", "connack_properties", b);
    for (n, code) in [
        ("connack_not_authorized", m5::ConnectReturnCode::NotAuthorized),
        ("connack_bad_auth_method", m5::ConnectReturnCode::BadAuthenticationMethod),
        ("connack_packet_too_large", m5::ConnectReturnCode::PacketTooLarge),
    ] {
        let mut b = BytesMut::new();
        m5::ConnAck { session_present: false, code, properties: None }.write(&mut b).unwrap();
        out("v5", n, b);
    }

    let mut p = m5::Publish::new("a/b", Q5::AtMostOnce, "hello", None);
    let mut b = BytesMut::new();
    p.write(&mut b).unwrap();
    out("v5", "publish_qos0", b);
    p.retain = true;
    let mut b = BytesMut::new();
    p.write(&mut b).unwrap();
    out("v5", "publish_qos0_retain", b);
    let mut p = m5::Publish::new(
        "sensors/temp",
        Q5::AtLeastOnce,
        Bytes::from_static(b"{\"t\":21}"),
        Some(m5::PublishProperties {
            payload_format_indicator: Some(1),
            message_expiry_interval: Some(30),
            topic_alias: Some(3),
            response_topic: Some(s("reply/here")),
            correlation_data: Some(Bytes::from_static(b"\x01\x02")),
            user_properties: vec![up("unit", "c")],
            subscription_identifiers: vec![7, 300],
            content_type: Some(s("application/json")),
        }),
    );
    p.pkid = 11;
    let mut b = BytesMut::new();
    p.write(&mut b).unwrap();
    out("v5", "publish_qos1_properties", b);
    // empty topic with an alias
    let mut p = m5::Publish::new(
        "",
        Q5::AtMostOnce,
        "x",
        Some(m5::PublishProperties {
            topic_alias: Some(3),
            ..Default::default()
        }),
    );
    p.retain = false;
    let mut b = BytesMut::new();
    p.write(&mut b).unwrap();
    out("v5", "publish_alias_empty_topic", b);

    let mut b = BytesMut::new();
    m5::PubAck::new(7, None).write(&mut b).unwrap();
    out("v5", "puback_success", b);
    let mut b = BytesMut::new();
    let mut a = m5::PubAck::new(7, None);
    a.reason = m5::PubAckReason::NoMatchingSubscribers;
    a.write(&mut b).unwrap();
    out("v5", "puback_no_subscribers", b);
    let mut b = BytesMut::new();
    let mut a = m5::PubAck::new(
        7,
        Some(m5::PubAckProperties {
            reason_string: Some(s("denied")),
            user_properties: vec![up("a", "b")],
        }),
    );
    a.reason = m5::PubAckReason::NotAuthorized;
    a.write(&mut b).unwrap();
    out("v5", "puback_not_authorized_props", b);
    let mut b = BytesMut::new();
    m5::PubRec::new(8, None).write(&mut b).unwrap();
    out("v5", "pubrec_success", b);
    let mut b = BytesMut::new();
    let mut a = m5::PubRec::new(8, None);
    a.reason = m5::PubRecReason::QuotaExceeded;
    a.write(&mut b).unwrap();
    out("v5", "pubrec_quota", b);
    let mut b = BytesMut::new();
    m5::PubRel::new(9, None).write(&mut b).unwrap();
    out("v5", "pubrel_success", b);
    let mut b = BytesMut::new();
    let mut a = m5::PubRel::new(9, None);
    a.reason = m5::PubRelReason::PacketIdentifierNotFound;
    a.write(&mut b).unwrap();
    out("v5", "pubrel_not_found", b);
    let mut b = BytesMut::new();
    m5::PubComp::new(10, None).write(&mut b).unwrap();
    out("v5", "pubcomp_success", b);

    let mut f2 = m5::Filter::new("b/c", Q5::ExactlyOnce);
    f2.nolocal = true;
    f2.preserve_retain = true;
    f2.retain_forward_rule = m5::RetainForwardRule::OnNewSubscribe;
    let mut f3 = m5::Filter::new("d/+/e", Q5::AtMostOnce);
    f3.retain_forward_rule = m5::RetainForwardRule::Never;
    let mut sub = m5::Subscribe::new_many(
        vec![m5::Filter::new("a/#", Q5::AtLeastOnce), f2, f3],
        Some(m5::SubscribeProperties { id: Some(42), user_properties: vec![up("s", "t")] }),
    );
    sub.pkid = 4;
    let mut b = BytesMut::new();
    sub.write(&mut b).unwrap();
    out("v5", "subscribe_options", b);
    let mut sub = m5::Subscribe::new(m5::Filter::new("a/b", Q5::AtMostOnce), None);
    sub.pkid = 5;
    let mut b = BytesMut::new();
    sub.write(&mut b).unwrap();
    out("v5", "subscribe_minimal", b);

    let mut b = BytesMut::new();
    m5::SubAck {
        pkid: 4,
        return_codes: vec![
            m5::SubscribeReasonCode::Success(Q5::AtMostOnce),
            m5::SubscribeReasonCode::Success(Q5::AtLeastOnce),
            m5::SubscribeReasonCode::Success(Q5::ExactlyOnce),
            m5::SubscribeReasonCode::NotAuthorized,
            m5::SubscribeReasonCode::TopicFilterInvalid,
            m5::SubscribeReasonCode::QuotaExceeded,
            m5::SubscribeReasonCode::SharedSubscriptionsNotSupported,
            m5::SubscribeReasonCode::WildcardSubscriptionsNotSupported,
        ],
        properties: Some(m5::SubAckProperties {
            reason_string: Some(s("mixed")),
            user_properties: vec![],
        }),
    }
    .write(&mut b)
    .unwrap();
    out("v5", "suback_reasons", b);

    let mut b = BytesMut::new();
    let mut u = m5::Unsubscribe::new("a/b", None);
    u.pkid = 6;
    u.filters.push(s("c/#"));
    u.write(&mut b).unwrap();
    out("v5", "unsubscribe", b);
    let mut b = BytesMut::new();
    m5::UnsubAck {
        pkid: 6,
        reasons: vec![m5::UnsubAckReason::Success, m5::UnsubAckReason::NoSubscriptionExisted],
        properties: None,
    }
    .write(&mut b)
    .unwrap();
    out("v5", "unsuback", b);
    let mut b = BytesMut::new();
    m5::PingReq::write(&mut b).unwrap();
    out("v5", "pingreq", b);
    let mut b = BytesMut::new();
    m5::PingResp::write(&mut b).unwrap();
    out("v5", "pingresp", b);
    let mut b = BytesMut::new();
    m5::Disconnect::new(m5::DisconnectReasonCode::NormalDisconnection).write(&mut b).unwrap();
    out("v5", "disconnect_normal", b);
    let mut b = BytesMut::new();
    m5::Disconnect {
        reason_code: m5::DisconnectReasonCode::SessionTakenOver,
        properties: Some(m5::DisconnectProperties {
            session_expiry_interval: Some(0),
            reason_string: Some(s("another client")),
            user_properties: vec![],
            server_reference: Some(s("other.example")),
        }),
    }
    .write(&mut b)
    .unwrap();
    out("v5", "disconnect_properties", b);

}
